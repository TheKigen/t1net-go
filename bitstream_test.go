func TestHuffmanTree(t *testing.T) {
	hp := getHuffProcessor()

	// Verify that the tree was built: root node should have non-zero population
	if hp.nodes[0].pop == 0 {
		t.Fatal("root node has zero population")
	}

	// Verify a known leaf: 'e' (index 101) should have the shortest code
	// since it has the highest frequency (2872 + boost)
	eLeaf := hp.leaves['e']
	if eLeaf.numBits == 0 {
		t.Fatal("leaf 'e' has zero numBits")
	}
	// 'e' should have fewer bits than a rare character like 0x80
	rareLeaf := hp.leaves[0x80]
	if eLeaf.numBits >= rareLeaf.numBits {
		t.Errorf("'e' (%d bits) should have fewer bits than 0x80 (%d bits)", eLeaf.numBits, rareLeaf.numBits)
	}
}

func TestBitsRemaining(t *testing.T) {
	reader := newBitStreamReader([]byte{0xFF, 0xFF})
	if reader.BitsRemaining() != 16 {
		t.Errorf("BitsRemaining: got %d, want 16", reader.BitsRemaining())
	}
	reader.ReadBits(5)
	if reader.BitsRemaining() != 11 {
		t.Errorf("BitsRemaining after read: got %d, want 11", reader.BitsRemaining())
	}
}

func TestReadHuffString(t *testing.T) {
	// "Tribes" encoded with Huffman, generated by Darkstar's WriteHuffString
	data := []byte{0x0d, 0x56, 0xc6, 0xbb, 0x6f}
	reader := newBitStreamReader(data)
	s, err := reader.ReadHuffString()
	if err != nil {
		t.Fatal(err)
	}
	if s != "Tribes" {
		t.Errorf("ReadHuffString: got %q, want %q", s, "Tribes")
	}
}


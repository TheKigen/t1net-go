func TestReadBits(t *testing.T) {
	// Byte 0xA5 = 10100101 in binary
	// LSB-first reading: bit0=1, bit1=0, bit2=1, bit3=0, bit4=0, bit5=1, bit6=0, bit7=1
	reader := newBitStreamReader([]byte{0xA5})

	// Read 4 bits: should get 0101 = 5 (bits 0-3: 1,0,1,0 -> LSB first = 0101 = 5)
	val, err := reader.ReadBits(4)
	if err != nil {
		t.Fatal(err)
	}
	if val != 5 {
		t.Errorf("ReadBits(4): got %d, want 5", val)
	}

	// Read next 4 bits: should get 1010 = 10 (bits 4-7: 0,1,0,1 -> LSB first = 1010 = 10)
	val, err = reader.ReadBits(4)
	if err != nil {
		t.Fatal(err)
	}
	if val != 10 {
		t.Errorf("ReadBits(4): got %d, want 10", val)
	}
}

func TestReadBitsMultiByte(t *testing.T) {
	// Read 16 bits across two bytes: 0x01, 0x00 -> little-endian uint16 = 1
	reader := newBitStreamReader([]byte{0x01, 0x00})
	val, err := reader.ReadBits(16)
	if err != nil {
		t.Fatal(err)
	}
	if val != 1 {
		t.Errorf("ReadBits(16): got %d, want 1", val)
	}
}

func TestReadBitsOverflow(t *testing.T) {
	reader := newBitStreamReader([]byte{0xFF})
	_, err := reader.ReadBits(9) // Only 8 bits available
	if err == nil {
		t.Fatal("expected error reading past end of buffer")
	}
}

